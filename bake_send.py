"""Bake send.png / send_over.png / send_click.png as data URLs into
injects/aa-send-data.js so the live bundle can swap states inline.
"""
import base64, io, pathlib
from PIL import Image
import numpy as np

ROOT = pathlib.Path(__file__).parent
ASSETS = ROOT / "assets"
OUT_JS = ROOT / "injects" / "aa-send-data.js"

def tight_crop(path):
    im = Image.open(path).convert("RGBA")
    a = np.array(im.split()[-1])
    ys, xs = np.where(a > 30)
    if not len(xs):
        bbox = im.getbbox()
    else:
        bbox = (int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1)
    return im.crop(bbox)

def to_data_url(im):
    buf = io.BytesIO()
    im.save(buf, format="PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode("ascii")

normal = tight_crop(ASSETS / "send.png")
hover  = tight_crop(ASSETS / "send_over.png")
click_ = tight_crop(ASSETS / "send_click.png")

print(f"send normal: {normal.size}, hover: {hover.size}, click: {click_.size}")

js = (
    "/* aa-send-data.js — generated by bake_send.py. Send-button states as data URLs. */\n"
    "(function(){\n"
    f"  window.__CB_SEND_NORMAL = '{to_data_url(normal)}';\n"
    f"  window.__CB_SEND_HOVER  = '{to_data_url(hover)}';\n"
    f"  window.__CB_SEND_CLICK  = '{to_data_url(click_)}';\n"
    f"  window.__CB_SEND_W = {normal.size[0]};\n"
    f"  window.__CB_SEND_H = {normal.size[1]};\n"
    "})();\n"
)
OUT_JS.write_text(js, encoding="utf-8")
print(f"wrote {OUT_JS}  {OUT_JS.stat().st_size} bytes")

static int parsePort(const char* s, int fallback) {
    if (!s || !*s) return fallback;
    char* end = NULL;
    long v = strtol(s, &end, 10);
    if (end == s || v < 1 || v > 65535) return fallback;
    return (int)v;
}

static std::wstring widen(const std::string& s) {
    if (s.empty()) return L"";
    int n = MultiByteToWideChar(CP_UTF8, 0, s.c_str(), (int)s.size(), NULL, 0);
    std::wstring w(n, 0);
    MultiByteToWideChar(CP_UTF8, 0, s.c_str(), (int)s.size(), &w[0], n);
    return w;
}
static std::string narrow(const std::wstring& w) {
    if (w.empty()) return "";
    int n = WideCharToMultiByte(CP_UTF8, 0, w.c_str(), (int)w.size(), NULL, 0, NULL, NULL);
    std::string s(n, 0);
    WideCharToMultiByte(CP_UTF8, 0, w.c_str(), (int)w.size(), &s[0], n, NULL, NULL);
    return s;
}
static std::string lower(std::string s) {
    for (auto& c : s) c = (char)tolower((unsigned char)c);
    return s;
}

// Locate config.ini next to the .exe's parent directory (the CBE repo root).
// Falls back to %CD%\config.ini if the exe lives somewhere unexpected.
static std::wstring configIniPath() {
    wchar_t exePath[MAX_PATH];
    GetModuleFileNameW(NULL, exePath, MAX_PATH);
    // exe is at ...\Claude Codex Black\bin\CBE-Bridge-X.exe ; go up two.
    wchar_t* slash = wcsrchr(exePath, L'\\');
    if (slash) *slash = 0;                  // strip filename
    slash = wcsrchr(exePath, L'\\');
    if (slash) *slash = 0;                  // strip "\bin"
    std::wstring p(exePath);
    p += L"\\config.ini";
    return p;
}


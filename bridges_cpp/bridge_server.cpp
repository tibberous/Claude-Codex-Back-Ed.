static void selfProbe(wchar_t* outBuf, size_t outChars) {
    SOCKET s = socket(AF_INET, SOCK_STREAM, IPPROTO_TCP);
    if (s == INVALID_SOCKET) { swprintf_s(outBuf, outChars, L"socket() failed"); return; }
    DWORD tv = 3000;
    setsockopt(s, SOL_SOCKET, SO_RCVTIMEO, (const char*)&tv, sizeof(tv));
    sockaddr_in addr; memset(&addr, 0, sizeof(addr));
    addr.sin_family = AF_INET;
    addr.sin_port = htons((u_short)g_port);
    inet_pton(AF_INET, "127.0.0.1", &addr.sin_addr);
    if (connect(s, (sockaddr*)&addr, sizeof(addr)) == SOCKET_ERROR) {
        swprintf_s(outBuf, outChars, L"connect failed: %d", WSAGetLastError());
        closesocket(s); return;
    }
    const char* req = "GET / HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\n\r\n";
    send(s, req, (int)strlen(req), 0);
    char buf[1024] = {0};
    int n = recv(s, buf, sizeof(buf) - 1, 0);
    closesocket(s);
    if (n <= 0) { swprintf_s(outBuf, outChars, L"recv failed"); return; }
    buf[n] = 0;
    char* nl = strstr(buf, "\r\n");
    if (nl) *nl = 0;
    swprintf_s(outBuf, outChars, L"Test OK\n\nResponse first line:\n%hs", buf);
}


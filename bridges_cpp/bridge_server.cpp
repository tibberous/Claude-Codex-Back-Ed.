// Tiny JSON scanner: find every "name":"<value>" occurrence in `body`. Good
// enough for Ollama's /api/tags response. Won't handle escaped quotes inside
// the value (Ollama tags don't have them).
static std::vector<std::string> scanJsonNameFields(const std::string& body) {
    std::vector<std::string> out;
    const char* p = body.c_str();
    while ((p = strstr(p, "\"name\"")) != NULL) {
        p += 6;
        while (*p && *p != ':') ++p;
        if (!*p) break;
        ++p;
        while (*p && (*p == ' ' || *p == '\t')) ++p;
        if (*p != '"') continue;
        ++p;
        const char* end = p;
        while (*end && *end != '"') ++end;
        if (!*end) break;
        out.emplace_back(p, end);
        p = end + 1;
    }
    return out;
}

static std::vector<std::string> staticModelsFor(const std::string& target) {
    // Small curated lists per provider. The bridge can't enforce these — the
    // upstream web UI is still the source of truth — but giving the user
    // *something* to pick keeps the menu usable until real discovery lands.
    std::string t = lower(target);
    if (t == "chatgpt") return { "gpt-4o", "gpt-4o-mini", "gpt-4.1", "o1-preview", "o1-mini", "gpt-5.4", "gpt-5.5" };
    if (t == "grok")    return { "grok-2", "grok-2-mini", "grok-beta" };
    if (t == "gemini")  return { "gemini-2.5-pro", "gemini-2.5-flash", "gemini-2.0-pro" };
    if (t == "claude")  return { "claude-opus-4-7", "claude-sonnet-4-6", "claude-haiku-4-5" };
    if (t == "copilot") return { "gpt-4o", "gpt-4.1", "o1-preview" };
    return { "(no models)" };
}

static std::vector<std::string> discoverModels() {
    std::string t = lower(std::string(TARGET_NAME));
    if (t == "ollama") {
        // Real HTTP probe — Ollama's default daemon port is 11434.
        std::string body = httpGet("127.0.0.1", 11434, "/api/tags", 1500);
        if (!body.empty()) {
            auto names = scanJsonNameFields(body);
            if (!names.empty()) return names;
        }
        // Daemon unreachable or empty list.
        return { "(ollama not running)" };
    }
    return staticModelsFor(t);
}

static void refreshModels() {
    auto fresh = discoverModels();
    std::lock_guard<std::mutex> lock(g_modelsMtx);
    g_models = std::move(fresh);
    // If the saved model isn't in the list, leave g_currentModel as-is —
    // user may have hand-edited config.ini; respect that.
    if (g_currentModel.empty() && !g_models.empty()) {
        g_currentModel = g_models.front();
    }
}


// CBE-Bridge-<TARGET>.exe — WinSock HTTP/1.1 server + system tray icon + per-target
// Settings menu with model discovery and config.ini persistence.
//
// Threads:
//   - main: hidden message-only window + Shell_NotifyIcon + context menu.
//   - worker: blocking accept() loop, 200/OK JSON reply per connection.
//
// Tray menu:
//   Settings   → submenu populated by discoverModels(); selected model is
//                checked and saved to config.ini under [<target>] model=<name>.
//   Status     → "running on 127.0.0.1:<port>" + connection count.
//   Information→ IP / port / endpoint / PID / current model.
//   Test       → in-process self-probe via local GET /.
//   About      → version + author.
//   Close      → NIM_DELETE icon + exit.
//
// Model discovery is target-specific:
//   - ollama: real HTTP GET http://127.0.0.1:11434/api/tags, parses model names.
//   - everything else: a small baked-in static list (see staticModelsFor()).
//
// Persistence: WritePrivateProfileStringW / GetPrivateProfileStringW against
// CBE's config.ini next to start.py. Section is the lowercased target.
//
// Target name + default port come from bridge_target_<name>.h (generated by
// build_bridges.ps1).


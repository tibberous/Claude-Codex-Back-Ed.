// Minimal blocking HTTP/1.1 client. Used to query Ollama's /api/tags for
// model discovery. host/port resolved at call site. Returns body on 200,
// empty string on failure.
static std::string httpGet(const char* host, int port, const char* path,
                           int timeoutMs = 1500) {
    SOCKET s = socket(AF_INET, SOCK_STREAM, IPPROTO_TCP);
    if (s == INVALID_SOCKET) return "";
    DWORD tv = (DWORD)timeoutMs;
    setsockopt(s, SOL_SOCKET, SO_RCVTIMEO, (const char*)&tv, sizeof(tv));
    setsockopt(s, SOL_SOCKET, SO_SNDTIMEO, (const char*)&tv, sizeof(tv));

    sockaddr_in addr; memset(&addr, 0, sizeof(addr));
    addr.sin_family = AF_INET;
    addr.sin_port = htons((u_short)port);
    if (inet_pton(AF_INET, host, &addr.sin_addr) != 1) {
        // Resolve hostname (e.g. "localhost").
        addrinfo hints; memset(&hints, 0, sizeof(hints));
        hints.ai_family = AF_INET; hints.ai_socktype = SOCK_STREAM;
        addrinfo* res = NULL;
        char portBuf[12]; _snprintf_s(portBuf, sizeof(portBuf), _TRUNCATE, "%d", port);
        if (getaddrinfo(host, portBuf, &hints, &res) != 0 || !res) { closesocket(s); return ""; }
        memcpy(&addr, res->ai_addr, sizeof(addr));
        freeaddrinfo(res);
    }
    if (connect(s, (sockaddr*)&addr, sizeof(addr)) == SOCKET_ERROR) { closesocket(s); return ""; }

    char req[1024];
    int reqLen = _snprintf_s(req, sizeof(req), _TRUNCATE,
        "GET %s HTTP/1.1\r\nHost: %s:%d\r\nConnection: close\r\nUser-Agent: CBE-Bridge-%s/1.0\r\n\r\n",
        path, host, port, TARGET_NAME);
    if (send(s, req, reqLen, 0) != reqLen) { closesocket(s); return ""; }

    std::string raw;
    char buf[2048];
    for (;;) {
        int n = recv(s, buf, sizeof(buf), 0);
        if (n <= 0) break;
        raw.append(buf, buf + n);
        if (raw.size() > 1024 * 1024) break;     // sanity cap
    }
    closesocket(s);

    // Skip headers; only return body if 200.
    if (raw.compare(0, 9, "HTTP/1.1 ") != 0) return "";
    if (raw.compare(9, 3, "200") != 0) return "";
    size_t bodyStart = raw.find("\r\n\r\n");
    if (bodyStart == std::string::npos) return "";
    return raw.substr(bodyStart + 4);
}


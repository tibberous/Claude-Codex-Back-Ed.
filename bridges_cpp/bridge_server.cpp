// Minimal blocking HTTP/1.1 client. Used to query Ollama's /api/tags for
// model discovery. host/port resolved at call site. Returns body on 200,
// empty string on failure.
static std::string httpGet(const char* host, int port, const char* path,
                           int timeoutMs = 1500) {
    SOCKET s = socket(AF_INET, SOCK_STREAM, IPPROTO_TCP);
    if (s == INVALID_SOCKET) return "";
    DWORD tv = (DWORD)timeoutMs;
    setsockopt(s, SOL_SOCKET, SO_RCVTIMEO, (const char*)&tv, sizeof(tv));
    setsockopt(s, SOL_SOCKET, SO_SNDTIMEO, (const char*)&tv, sizeof(tv));

    sockaddr_in addr; memset(&addr, 0, sizeof(addr));
    addr.sin_family = AF_INET;
    addr.sin_port = htons((u_short)port);
    if (inet_pton(AF_INET, host, &addr.sin_addr) != 1) {
        // Resolve hostname (e.g. "localhost").
        addrinfo hints; memset(&hints, 0, sizeof(hints));
        hints.ai_family = AF_INET; hints.ai_socktype = SOCK_STREAM;
        addrinfo* res = NULL;
        char portBuf[12]; _snprintf_s(portBuf, sizeof(portBuf), _TRUNCATE, "%d", port);
        if (getaddrinfo(host, portBuf, &hints, &res) != 0 || !res) { closesocket(s); return ""; }
        memcpy(&addr, res->ai_addr, sizeof(addr));
        freeaddrinfo(res);
    }
    if (connect(s, (sockaddr*)&addr, sizeof(addr)) == SOCKET_ERROR) { closesocket(s); return ""; }

    char req[1024];
    int reqLen = _snprintf_s(req, sizeof(req), _TRUNCATE,
        "GET %s HTTP/1.1\r\nHost: %s:%d\r\nConnection: close\r\nUser-Agent: CBE-Bridge-%s/1.0\r\n\r\n",
        path, host, port, TARGET_NAME);
    if (send(s, req, reqLen, 0) != reqLen) { closesocket(s); return ""; }

    std::string raw;
    char buf[2048];
    for (;;) {
        int n = recv(s, buf, sizeof(buf), 0);
        if (n <= 0) break;
        raw.append(buf, buf + n);
        if (raw.size() > 1024 * 1024) break;     // sanity cap
    }
    closesocket(s);

    // Skip headers; only return body if 200.
    if (raw.compare(0, 9, "HTTP/1.1 ") != 0) return "";
    if (raw.compare(9, 3, "200") != 0) return "";
    size_t bodyStart = raw.find("\r\n\r\n");
    if (bodyStart == std::string::npos) return "";
    return raw.substr(bodyStart + 4);
}

// -------------------------------------------------------- model discovery --

// Tiny JSON scanner: find every "name":"<value>" occurrence in `body`. Good
// enough for Ollama's /api/tags response. Won't handle escaped quotes inside
// the value (Ollama tags don't have them).
static std::vector<std::string> scanJsonNameFields(const std::string& body) {
    std::vector<std::string> out;
    const char* p = body.c_str();
    while ((p = strstr(p, "\"name\"")) != NULL) {
        p += 6;
        while (*p && *p != ':') ++p;
        if (!*p) break;
        ++p;
        while (*p && (*p == ' ' || *p == '\t')) ++p;
        if (*p != '"') continue;
        ++p;
        const char* end = p;
        while (*end && *end != '"') ++end;
        if (!*end) break;
        out.emplace_back(p, end);
        p = end + 1;
    }
    return out;
}

static std::vector<std::string> staticModelsFor(const std::string& target) {
    // Small curated lists per provider. The bridge can't enforce these — the
    // upstream web UI is still the source of truth — but giving the user
    // *something* to pick keeps the menu usable until real discovery lands.
    std::string t = lower(target);
    if (t == "chatgpt") return { "gpt-4o", "gpt-4o-mini", "gpt-4.1", "o1-preview", "o1-mini", "gpt-5.4", "gpt-5.5" };
    if (t == "grok")    return { "grok-2", "grok-2-mini", "grok-beta" };
    if (t == "gemini")  return { "gemini-2.5-pro", "gemini-2.5-flash", "gemini-2.0-pro" };
    if (t == "claude")  return { "claude-opus-4-7", "claude-sonnet-4-6", "claude-haiku-4-5" };
    if (t == "copilot") return { "gpt-4o", "gpt-4.1", "o1-preview" };
    return { "(no models)" };
}

static std::vector<std::string> discoverModels() {
    std::string t = lower(std::string(TARGET_NAME));
    if (t == "ollama") {
        // Real HTTP probe — Ollama's default daemon port is 11434.
        std::string body = httpGet("127.0.0.1", 11434, "/api/tags", 1500);
        if (!body.empty()) {
            auto names = scanJsonNameFields(body);
            if (!names.empty()) return names;
        }
        // Daemon unreachable or empty list.
        return { "(ollama not running)" };
    }
    return staticModelsFor(t);
}

static void refreshModels() {
    auto fresh = discoverModels();
    std::lock_guard<std::mutex> lock(g_modelsMtx);
    g_models = std::move(fresh);
    // If the saved model isn't in the list, leave g_currentModel as-is —
    // user may have hand-edited config.ini; respect that.
    if (g_currentModel.empty() && !g_models.empty()) {
        g_currentModel = g_models.front();
    }
}

// ----------------------------------------------------------- HTTP server ---

// Two protocols speak to this server on the same port:
//   - HTTP/1.1 (curl, browser tests): first byte is M/G/P/O/H (GET, POST,
//     PUT, OPTIONS, HEAD). Respond with HTTP/1.1 200 + JSON body.
//   - SuperGrok bridge protocol (start.py runChatCommand): newline-delimited
//     JSON. First byte is '{'. Respond with a JSON line + LF, no HTTP framing.
//
// For both, the body is the same status JSON. This lets start.py's status
// probe AND a curl healthcheck both see "ok":true.
static void serverWorker() {
    for (;;) {
        SOCKET client = accept(g_listenSock, NULL, NULL);
        if (client == INVALID_SOCKET) {
            if (g_listenSock == INVALID_SOCKET) return;
            continue;
        }
        g_connCount.fetch_add(1);

        char req[4096] = {0};
        int reqLen = recv(client, req, sizeof(req) - 1, 0);
        bool isJson = (reqLen > 0 && req[0] == '{');

        std::string model;
        {
            std::lock_guard<std::mutex> lock(g_modelsMtx);
            model = g_currentModel;
        }

        // Decide what kind of reply the client expects.
        if (isJson) {
            // SuperGrok bridge protocol. start.py sends one JSON object per
            // line and expects one JSON object back (also newline-terminated).
            // Sniff the "action" field cheaply so we can give status / chat
            // probes the right shape.
            const char* action = strstr(req, "\"action\"");
            bool isStatus = (action && strstr(action, "status"));
            bool isChat   = (action && strstr(action, "\"chat\""));
            bool isChatResult = (action && strstr(action, "chat-result"));

            char body[1024];
            if (isChat) {
                // MVP chat response: accept the job synchronously and reply
                // with a canned "answer". Real chat driver (QtWebEngine /
                // Ollama /api/chat passthrough) plugs in here later.
                _snprintf_s(body, sizeof(body), _TRUNCATE,
                    "{\"ok\":true,\"accepted\":false,\"target\":\"%s\",\"port\":%d,"
                    "\"model\":\"%s\",\"answer\":\"[CBE-Bridge-%s MVP] received your prompt. "
                    "Real chat driver not yet wired — this is a placeholder reply so the round-trip can "
                    "complete and chat.log can capture both directions.\",\"server\":\"CBE-Bridge-%s/1.0\"}\n",
                    TARGET_NAME, g_port, model.c_str(), TARGET_NAME, TARGET_NAME);
            } else if (isChatResult) {
                // Polled after an async chat ack; we're synchronous so there
                // is no pending job. Surface a clean "done" signal.
                _snprintf_s(body, sizeof(body), _TRUNCATE,
                    "{\"ok\":true,\"accepted\":false,\"target\":\"%s\",\"port\":%d,"
                    "\"model\":\"%s\",\"answer\":\"\",\"server\":\"CBE-Bridge-%s/1.0\"}\n",
                    TARGET_NAME, g_port, model.c_str(), TARGET_NAME);
            } else {
                // status, ping, anything else.
                _snprintf_s(body, sizeof(body), _TRUNCATE,
                    "{\"ok\":true,\"target\":\"%s\",\"port\":%d,\"model\":\"%s\","
                    "\"service\":\"SuperGrok Bridge\",\"server\":\"CBE-Bridge-%s/1.0\"}\n",
                    TARGET_NAME, g_port, model.c_str(), TARGET_NAME);
                (void)isStatus;
            }
            int bodyLen = (int)strlen(body);
            int sent = 0;
            while (sent < bodyLen) {
                int n = send(client, body + sent, bodyLen - sent, 0);
                if (n == SOCKET_ERROR || n == 0) break;
                sent += n;
            }
        } else {
            // HTTP/1.1 path — same payload, with headers.
            char body[512];
            int bodyLen = _snprintf_s(body, sizeof(body), _TRUNCATE,
                "{\"ok\":true,\"target\":\"%s\",\"port\":%d,\"model\":\"%s\",\"server\":\"CBE-Bridge-%s/1.0\"}\r\n",
                TARGET_NAME, g_port, model.c_str(), TARGET_NAME);
            char resp[1024];
            int respLen = _snprintf_s(resp, sizeof(resp), _TRUNCATE,
                "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: %d\r\n"
                "Connection: close\r\nServer: CBE-Bridge-%s/1.0\r\n\r\n%s",
                bodyLen, TARGET_NAME, body);
            int sent = 0;
            while (sent < respLen) {
                int n = send(client, resp + sent, respLen - sent, 0);
                if (n == SOCKET_ERROR || n == 0) break;
                sent += n;
            }
        }
        shutdown(client, SD_SEND);
        closesocket(client);
    }
}

static bool startServer(int port) {
    WSADATA wsa;
    if (WSAStartup(MAKEWORD(2, 2), &wsa) != 0) return false;
    g_listenSock = socket(AF_INET, SOCK_STREAM, IPPROTO_TCP);
    if (g_listenSock == INVALID_SOCKET) return false;
    int yes = 1;
    setsockopt(g_listenSock, SOL_SOCKET, SO_REUSEADDR, (const char*)&yes, sizeof(yes));
    sockaddr_in addr; memset(&addr, 0, sizeof(addr));
    addr.sin_family = AF_INET;
    addr.sin_port = htons((u_short)port);
    inet_pton(AF_INET, "127.0.0.1", &addr.sin_addr);
    if (bind(g_listenSock, (sockaddr*)&addr, sizeof(addr)) == SOCKET_ERROR) return false;
    if (listen(g_listenSock, 16) == SOCKET_ERROR) return false;
    std::thread(serverWorker).detach();
    return true;
}


// One global-ish buffer carrying the "stats only" preamble we always show on
// the Status dialog. The Test button appends curl results below this; the
// TDM_SET_ELEMENT_TEXT update overwrites the whole content area each click.
static void formatStatusPreamble(wchar_t* out, size_t outChars, const wchar_t* extra) {
    std::string model;
    {
        std::lock_guard<std::mutex> lock(g_modelsMtx);
        model = g_currentModel;
    }
    if (extra && *extra) {
        swprintf_s(out, outChars,
            L"CBE-Bridge-%hs running on 127.0.0.1:%d\n"
            L"Connections served: %d\n"
            L"Current model: %hs\n\n"
            L"--- curl GET http://127.0.0.1:%d/ ---\n%ls",
            TARGET_NAME, g_port, g_connCount.load(),
            model.empty() ? "(none)" : model.c_str(),
            g_port, extra);
    } else {
        swprintf_s(out, outChars,
            L"CBE-Bridge-%hs running on 127.0.0.1:%d\n"
            L"Connections served: %d\n"
            L"Current model: %hs\n\n"
            L"Click \"Run curl test\" to fetch http://127.0.0.1:%d/ and display the response inline.",
            TARGET_NAME, g_port, g_connCount.load(),
            model.empty() ? "(none)" : model.c_str(),
            g_port);
    }
}


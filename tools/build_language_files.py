def _xml_for_locale(code: str, english_name: str, native_name: str, strings: dict[str, str]) -> str:
    lines = ['<?xml version="1.0" encoding="UTF-8"?>']
    lines.append(f'<strings locale="{escape(code)}" name="{escape(english_name)}" native="{escape(native_name)}">')
    for key in sorted(strings.keys()):
        value = strings[key]
        lines.append(f'  <s id="{escape(key)}">{escape(value)}</s>')
    lines.append('</strings>')
    return '\n'.join(lines) + '\n'


def main() -> int:
    LANGUAGES_DIR.mkdir(parents=True, exist_ok=True)
    english = TRANSLATIONS["en"]
    written = 0
    for code, english_name, native_name in LOCALES:
        # Start from the English table so every locale has the full key set;
        # overlay the locale's own translations on top. Missing keys stay
        # English, which is the documented fallback behavior.
        merged = dict(english)
        merged.update(TRANSLATIONS.get(code, {}))
        xml = _xml_for_locale(code, english_name, native_name, merged)
        out_path = LANGUAGES_DIR / f"{code}.xml"
        out_path.write_text(xml, encoding="utf-8")
        written += 1
        print(f"WROTE {out_path}  keys={len(merged)}")
    print(f"\ndone. wrote {written} locale files into {LANGUAGES_DIR}")
    return 0



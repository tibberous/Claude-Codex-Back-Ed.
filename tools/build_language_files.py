"""
build_language_files.py

Single-source generator for c:\\Users\\moren\\Desktop\\Claude Codex Black\\languages\\*.xml.

The translation table is a Python dict keyed by ISO 639-1 / IETF tag, with the
SAME key set in every locale. English is authoritative — if a non-English
locale lacks a key, the loader falls back to English at runtime, so missing
strings never crash.

To add a new key:
  1. Add it to TRANSLATIONS['en'] with the English text.
  2. Add the same key to every other locale with the translated text. Locales
     missing the key fall back to English silently.
  3. Run this script. It writes one xml file per locale.

To add a new locale:
  1. Add a new top-level key to TRANSLATIONS with the locale code.
  2. Translate every key (or omit; missing keys fall back to English).
  3. Run this script.
"""


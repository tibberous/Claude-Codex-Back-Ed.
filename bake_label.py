"""Tight-crop label-alpha.png + label-alpha-hover.png to their non-transparent bbox,
then emit injects/label-data.js with both as base64 data URLs on window.__CB.
"""

import base64, pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).parent
ASSETS = ROOT / "assets"
OUT_JS = ROOT / "injects" / "aa-label-data.js"

def tight_crop(path):
    """Crop to alpha>30 bbox — keeps pill + drop shadow, drops soft outer glow."""
    import numpy as np
    im = Image.open(path).convert("RGBA")
    a = np.array(im.split()[-1])
    ys, xs = np.where(a > 30)
    if not len(xs):
        print(f"{path.name}: WARN no alpha>30 pixels — using getbbox()")
        bbox = im.getbbox()
    else:
        bbox = (int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1)
    cropped = im.crop(bbox)
    print(f"{path.name}: {im.size} -> {cropped.size}  bbox={bbox}")
    return cropped

def to_data_url(im):
    import io
    buf = io.BytesIO()
    im.save(buf, format="PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode("ascii")

normal = tight_crop(ASSETS / "label-alpha.png")
hover  = tight_crop(ASSETS / "label-alpha-hover.png")

# NOTE: don't overwrite source PNGs — only emit the bundled data URLs

url_n = to_data_url(normal)
url_h = to_data_url(hover)

js = (
    "/* label-data.js — generated by bake_label.py. Exposes CBE label assets as data URLs. */\n"
    "(function(){\n"
    f"  window.__CB_LABEL_NORMAL = '{url_n}';\n"
    f"  window.__CB_LABEL_HOVER  = '{url_h}';\n"
    f"  window.__CB_LABEL_W = {normal.size[0]};\n"
    f"  window.__CB_LABEL_H = {normal.size[1]};\n"
    "})();\n"
)
OUT_JS.write_text(js, encoding="utf-8")
print(f"wrote {OUT_JS}  size={OUT_JS.stat().st_size} bytes")
print(f"normal size: {normal.size}, hover size: {hover.size}")
